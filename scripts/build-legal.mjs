#!/usr/bin/env node
/**
 * Generates terms.html and privacy.html from the app's legal pages, so the website and
 * app2.heliotropeimaginal.com show the same text.
 *
 * Source of truth: HeliotropeImaginal repo, client/src/pages/legal/{terms,privacy}.tsx
 * and shared/legal.ts. Edit the text there, then re-run:
 *
 *   node scripts/build-legal.mjs [path/to/HeliotropeImaginal]
 *
 * Default app path: ../HeliotropeImaginal (sibling checkout).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const appRoot = resolve(process.argv[2] || resolve(siteRoot, '../HeliotropeImaginal'));

// --- constants from shared/legal.ts ---
const legalTs = readFileSync(resolve(appRoot, 'shared/legal.ts'), 'utf8');
const C = {};
for (const m of legalTs.matchAll(/export const (\w+) = '([^']*)';/g)) C[m[1]] = m[2];
for (const k of ['TERMS_VERSION', 'PRIVACY_VERSION', 'LEGAL_EFFECTIVE_DATE', 'LEGAL_ENTITY', 'LEGAL_ADDRESS', 'PRIVACY_OFFICER', 'SUPPORT_EMAIL']) {
  if (!(k in C)) throw new Error(`shared/legal.ts: missing ${k}`);
}

const SA_URLS = { SA_TERMS_URL: 'https://selfactual.ai/terms', SA_PRIVACY_URL: 'https://selfactual.ai/privacy' };

// Bracketed values are unresolved draft items: highlight them, as the app does.
const val = (v) => (v.startsWith('[') ? `<mark>${v}</mark>` : v);
const mail = `<a href="mailto:${C.SUPPORT_EMAIL}">${C.SUPPORT_EMAIL}</a>`;

function convert(tsx, file) {
  const body = tsx.match(/<LegalPageLayout[^>]*>([\s\S]*?)<\/LegalPageLayout>/);
  if (!body) throw new Error(`${file}: no <LegalPageLayout> body`);
  let h = body[1];

  h = h
    .replace(/\{mail\}/g, mail)
    .replace(/\{entity\}/g, val(C.LEGAL_ENTITY))
    .replace(/\{officer\}/g, val(C.PRIVACY_OFFICER))
    .replace(/<Todo>\{(\w+)\}<\/Todo>/g, (_, k) => {
      if (!(k in C)) throw new Error(`${file}: unknown constant ${k}`);
      return val(C[k]);
    })
    .replace(/<Todo>/g, '<mark>')
    .replace(/<\/Todo>/g, '</mark>')
    .replace(/\{' '\}/g, ' ')
    .replace(/<br \/>/g, '<br>')
    .replace(/href=\{(SA_\w+)\}/g, (_, k) => {
      if (!(k in SA_URLS)) throw new Error(`${file}: unknown URL ${k}`);
      return `href="${SA_URLS[k]}"`;
    })
    .replace(/href="\/privacy"/g, 'href="privacy.html"')
    .replace(/href="\/terms"/g, 'href="terms.html"')
    .replace(/className=/g, 'class=');

  // Anything JSX left over means the converter needs a new rule; fail rather than ship it.
  const leftover = h.match(/\{[^}]*\}/);
  if (leftover) throw new Error(`${file}: unconverted JSX expression ${leftover[0]}`);

  return h.replace(/^ {6}/gm, '        ').trim();
}

function page({ title, version, content }) {
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title} — Heliotrope Imaginal</title>
  <meta name="description" content="Heliotrope Imaginal ${title} for the AllStarTeams and Imaginal Agility workshops.">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Alexandria:wght@400;600;700;800&family=Sora:wght@300;400;500;600&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="style.css">
</head>
<body>
  <!-- GENERATED by scripts/build-legal.mjs from the HeliotropeImaginal app. Do not edit by hand. -->

  <nav class="navbar">
    <a href="index.html"><img src="images/Heliotrope-Imaginal-logo.horizongal.black-text.png" alt="Heliotrope Imaginal" class="navbar-logo" width="600" height="256"></a>
    <div class="navbar-buttons">
      <a href="index.html" class="btn btn-outline btn-sm">&larr; Back to home</a>
    </div>
  </nav>

  <div class="page-wrapper">
    <section class="card-section legal">
      <h1>${title}</h1>
      <p class="legal-meta">Version ${version} &middot; Effective ${val(C.LEGAL_EFFECTIVE_DATE)}</p>
      <article>
        ${content}
      </article>
    </section>

    <footer class="footer">
      <p>&copy; 2026 Heliotrope Imaginal. All rights reserved.</p>
      <p class="footer-links">
        <a href="terms.html">Terms of Use</a>
        <span aria-hidden="true"> &middot; </span>
        <a href="privacy.html">Privacy Policy</a>
      </p>
    </footer>
  </div>
</body>
</html>
`;
}

const pages = [
  { file: 'terms', title: 'Terms of Use', version: C.TERMS_VERSION },
  { file: 'privacy', title: 'Privacy Policy', version: C.PRIVACY_VERSION },
];
for (const p of pages) {
  const src = resolve(appRoot, `client/src/pages/legal/${p.file}.tsx`);
  const content = convert(readFileSync(src, 'utf8'), src);
  writeFileSync(resolve(siteRoot, `${p.file}.html`), page({ ...p, content }));
  console.log(`wrote ${p.file}.html (v${p.version})`);
}
